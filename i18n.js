  const XA = (window.XA = window.XA || {});
  const KEY = 'xa-lang';
  const pick = () => {
    let v = null; try { v = localStorage.getItem(KEY); } catch (e) { }
    if (v && I18N[v]) return v;
    return 'ko'; // 기본은 한국어
  };
  XA.I18N = I18N;
  XA.lang = pick();
  XA.locale = () => (I18N[XA.lang] || I18N.ko)._locale;
  XA.t = (k, p) => {
    let s = (I18N[XA.lang] || {})[k]; if (s == null) s = I18N.ko[k]; if (s == null) return k;
    return p ? s.replace(/\{(\w+)\}/g, (m, n) => (p[n] != null ? p[n] : m)) : s;
  };
  // 번역 가능한 에러: 언어를 바꾸면 같은 키로 다시 표시
  XA.err = (key, params) => { const e = new Error(XA.t(key, params)); e.key = key; e.params = params; return e; };

  function apply(root) {
    root = root || document;
    const t = XA.t;
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); el.setAttribute('aria-label', t(el.dataset.i18nTitle)); });
    document.documentElement.lang = XA.lang;
    const page = document.body && document.body.dataset.page;
    document.title = t(page === 'privacy' ? 'privacy.docTitle' : 'doc.title');
    const md = document.querySelector('meta[name=description]'); if (md) md.content = t('doc.desc');
    document.querySelectorAll('[data-lang-toggle]').forEach((box) => {
      box.setAttribute('aria-label', t('lang.label'));
      box.innerHTML = Object.keys(I18N).map((l) => `<button type="button" data-lang="${l}" class="${l === XA.lang ? 'on' : ''}" aria-pressed="${l === XA.lang}" title="${I18N[l]._name}" lang="${l}">${I18N[l]._name}</button>`).join('');
      box.querySelectorAll('button').forEach((b) => b.addEventListener('click', () => XA.setLang(b.dataset.lang)));
    });
  }
  XA.applyI18n = apply;
  XA.setLang = (l) => {
    if (!I18N[l] || l === XA.lang) return;
    XA.lang = l; try { localStorage.setItem(KEY, l); } catch (e) { }
    apply(); document.dispatchEvent(new CustomEvent('langchange', { detail: l }));
  };
